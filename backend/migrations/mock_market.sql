-- ─────────────────────────────────────────────────────────────────────────────
-- Mock Market Data System — CaRo Exchange
-- Run via: POST /api/migrate/mock-market  (admin only)
-- Tables are all prefixed with mock_ to isolate from real trading tables
-- ─────────────────────────────────────────────────────────────────────────────

-- Virtual liquidity providers (no login, used only for generating volume)
CREATE TABLE IF NOT EXISTS mock_traders (
  id           INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
  trader_code  VARCHAR(20)  NOT NULL UNIQUE,
  created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Per-token 24-hour rolling statistics (one row per token, upserted each tick)
CREATE TABLE IF NOT EXISTS mock_market_stats (
  token             VARCHAR(10)     NOT NULL PRIMARY KEY,
  last_price        DECIMAL(15,2)   NOT NULL,
  open_price        DECIMAL(15,2)   NOT NULL,
  high_24h          DECIMAL(15,2)   NOT NULL,
  low_24h           DECIMAL(15,2)   NOT NULL,
  volume_24h        DECIMAL(20,4)   NOT NULL DEFAULT 0,
  change_24h        DECIMAL(10,4)   NOT NULL DEFAULT 0,
  trade_count_24h   INT             NOT NULL DEFAULT 0,
  market_cap        DECIMAL(24,2)   NOT NULL DEFAULT 0,
  stats_date        DATE            NOT NULL DEFAULT '2000-01-01',
  updated_at        TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Order book: open buy/sell levels generated by the engine
CREATE TABLE IF NOT EXISTS mock_orders (
  id          INT              NOT NULL AUTO_INCREMENT PRIMARY KEY,
  token       VARCHAR(10)      NOT NULL,
  side        ENUM('buy','sell') NOT NULL,
  price       DECIMAL(15,2)    NOT NULL,
  quantity    DECIMAL(15,4)    NOT NULL,
  remaining   DECIMAL(15,4)    NOT NULL,
  trader_id   INT              NOT NULL,
  status      ENUM('open','partial','filled','cancelled') NOT NULL DEFAULT 'open',
  created_at  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_book    (token, side, status, price),
  INDEX idx_created (created_at)
);

-- Trade execution history
CREATE TABLE IF NOT EXISTS mock_trades (
  id                BIGINT         NOT NULL AUTO_INCREMENT PRIMARY KEY,
  token             VARCHAR(10)    NOT NULL,
  price             DECIMAL(15,2)  NOT NULL,
  quantity          DECIMAL(15,4)  NOT NULL,
  value             DECIMAL(24,2)  NOT NULL,
  side              ENUM('buy','sell') NOT NULL DEFAULT 'buy',
  buyer_trader_id   INT,
  seller_trader_id  INT,
  executed_at       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_token_time (token, executed_at)
);

-- OHLC candlestick data (all intervals in one table)
CREATE TABLE IF NOT EXISTS mock_candles (
  id            BIGINT         NOT NULL AUTO_INCREMENT PRIMARY KEY,
  token         VARCHAR(10)    NOT NULL,
  interval_type ENUM('1m','5m','15m','1h','1d') NOT NULL,
  open_time     DATETIME       NOT NULL,
  close_time    DATETIME       NOT NULL,
  open_price    DECIMAL(15,2)  NOT NULL,
  high_price    DECIMAL(15,2)  NOT NULL,
  low_price     DECIMAL(15,2)  NOT NULL,
  close_price   DECIMAL(15,2)  NOT NULL,
  volume        DECIMAL(20,4)  NOT NULL DEFAULT 0,
  trade_count   INT            NOT NULL DEFAULT 0,
  UNIQUE KEY uq_candle (token, interval_type, open_time),
  INDEX idx_lookup (token, interval_type, open_time)
);